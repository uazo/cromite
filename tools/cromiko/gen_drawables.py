"""Writes the CromIKO vector drawables into a Chromium checkout.

These are the drawables in CromIKO-Boot-Animation.patch, CromIKO-Onboarding.patch
and CromIKO-New-Tab-Page.patch:
  - the animated mascot on the Android 12+ splash screen
  - the animated mascot on the welcome (first run) screen
  - the CromIKO logo on the new tab page

Usage (after changing the logo, the colors or the animations below):

  python3 gen_drawables.py cromiko-logo.svg ~/chromium/src
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from gen_icons import ACCENT, CHARCOAL, MONO_EVEN_ODD, load_paths, outline_points  # noqa: E402

RING = 'Pfad 7'
HIGHLIGHT = 'Pfad 8'
STAR = 'Pfad 18'
# Wordmark letters from left to right; the counters of "o" and "O" are cut out
# with even-odd filling.
WORDMARK = [['Pfad 13'], ['Pfad 17'], ['Pfad 14', 'Pfad 15'], ['Pfad 11'], ['Pfad 16'],
            ['Pfad 12'], ['Pfad 9', 'Pfad 10']]

THEME_RES = 'components/browser_ui/theme/android/java/res/drawable/'
SPLASH_ICON = THEME_RES + 'cromiko_splash_icon.xml'
WELCOME_MASCOT = THEME_RES + 'cromiko_welcome_mascot.xml'
NTP_LOGO = 'chrome/browser/ui/android/logo/java/res/drawable/ic_google_logo.xml'

# Day/night colors defined in components/browser_ui/theme (CromIKO-Boot-Animation.patch).
MASCOT_COLOR = '@color/cromiko_mascot_color'
ACCENT_COLOR = '@color/cromiko_accent_color'

GENERATED = 'Generated by tools/cromiko/gen_drawables.py from tools/cromiko/cromiko-logo.svg.'
NEW_FILE_HEADER = [
    '<?xml version="1.0" encoding="utf-8"?>',
    '<!--',
    'Copyright 2026 The CromIKO Authors',
    'License: GPL-3.0-only - https://spdx.org/licenses/GPL-3.0-only.html',
    GENERATED,
    '-->',
    '',
]

# The splash animation must stay under a second (windowSplashScreenAnimationDuration).
INTRO = {
    'mascot': [
        ('scaleX', 0.7, 1, 0, 600, 'overshoot'),
        ('scaleY', 0.7, 1, 0, 600, 'overshoot'),
        ('rotation', -10, 0, 0, 600, 'decelerate_cubic'),
    ],
    'star': [
        ('scaleX', 0, 1, 300, 450, 'overshoot'),
        ('scaleY', 0, 1, 300, 450, 'overshoot'),
        ('rotation', -90, 0, 300, 450, 'decelerate_cubic'),
    ],
}
# The welcome screen keeps moving gently after the intro.
LOOP = {
    'mascot': [('translateY', 0, -3, 700, 1400, 'accelerate_decelerate')],
    'star_twinkle': [
        ('scaleX', 1, 0.7, 900, 900, 'accelerate_decelerate'),
        ('scaleY', 1, 0.7, 900, 900, 'accelerate_decelerate'),
    ],
}


def bbox(paths, names):
    pts = [p for n in names for p in outline_points(paths[n])]
    xs, ys = [p[0] for p in pts], [p[1] for p in pts]
    return min(xs), min(ys), max(xs), max(ys)


def center(box):
    return (box[0] + box[2]) / 2, (box[1] + box[3]) / 2


def fmt(v):
    return ('%.4f' % v).rstrip('0').rstrip('.')


def group(indent, attrs, children):
    pad = ' ' * indent
    lines = [pad + '<group']
    lines += ['%s    android:%s="%s"' % (pad, k, v) for k, v in attrs]
    lines[-1] += '>'
    return lines + children + [pad + '</group>']


def path(indent, data, color, even_odd=False):
    pad = ' ' * indent
    lines = [pad + '<path']
    if even_odd:
        lines.append(pad + '    android:fillType="evenOdd"')
    lines.append(pad + '    android:pathData="%s"' % data)
    lines.append(pad + '    android:fillColor="%s"/>' % color)
    return lines


def mapping(s, tx, ty):
    return [('translateX', fmt(tx)), ('translateY', fmt(ty)), ('scaleX', fmt(s)),
            ('scaleY', fmt(s))]


def mascot_groups(paths, s, tx, ty, indent, twinkle):
    """The mascot with named groups for the animations, in canvas coordinates."""
    mbox = bbox(paths, MONO_EVEN_ODD + [RING, HIGHLIGHT, STAR])
    mcx, mcy = center(mbox)
    scx, scy = center(bbox(paths, [STAR]))
    body = group(indent + 4, mapping(s, tx, ty),
                 path(indent + 8, ' '.join(paths[n] for n in MONO_EVEN_ODD), MASCOT_COLOR, True)
                 + path(indent + 8, paths[RING], MASCOT_COLOR)
                 + path(indent + 8, paths[HIGHLIGHT], ACCENT_COLOR))
    star_pivot = [('pivotX', fmt(tx + s * scx)), ('pivotY', fmt(ty + s * scy))]
    star = group(indent + 8 + (4 if twinkle else 0), mapping(s, tx, ty),
                 path(indent + 12 + (4 if twinkle else 0), paths[STAR], ACCENT_COLOR))
    if twinkle:
        star = group(indent + 8, [('name', 'star_twinkle')] + star_pivot, star)
    star = group(indent + 4, [('name', 'star')] + star_pivot, star)
    return group(indent, [('name', 'mascot'), ('pivotX', fmt(tx + s * mcx)),
                          ('pivotY', fmt(ty + s * mcy))], body + star)


def animators(specs, repeat):
    lines = []
    for prop, start, end, offset, duration, interpolator in specs:
        lines.append('                <objectAnimator')
        if offset and not repeat:
            # A delayed intro is written as keyframes from time 0, so that the start value is
            # applied right away instead of the drawable's resting state until the delay ends.
            total = offset + duration
            lines += [
                '                    android:duration="%d">' % total,
                '                    <propertyValuesHolder',
                '                        android:propertyName="%s"' % prop,
                '                        android:valueType="floatType">',
                '                        <keyframe android:fraction="0" android:value="%s"/>'
                % fmt(start),
                '                        <keyframe android:fraction="%s" android:value="%s"/>'
                % (fmt(offset / total), fmt(start)),
                '                        <keyframe',
                '                            android:fraction="1"',
                '                            android:value="%s"' % fmt(end),
                '                            android:interpolator="@android:interpolator/%s"/>'
                % interpolator,
                '                    </propertyValuesHolder>',
                '                </objectAnimator>',
            ]
            continue
        lines.append('                    android:propertyName="%s"' % prop)
        lines.append('                    android:valueFrom="%s"' % fmt(start))
        lines.append('                    android:valueTo="%s"' % fmt(end))
        lines.append('                    android:valueType="floatType"')
        if offset:
            lines.append('                    android:startOffset="%d"' % offset)
        lines.append('                    android:duration="%d"' % duration)
        if repeat:
            lines.append('                    android:repeatCount="infinite"')
            lines.append('                    android:repeatMode="reverse"')
        lines.append('                    android:interpolator="@android:interpolator/%s"/>'
                     % interpolator)
    return lines


def animated_mascot(paths, canvas_w, canvas_h, fit_w, fit_h, loop):
    mbox = bbox(paths, MONO_EVEN_ODD + [RING, HIGHLIGHT, STAR])
    s = min(fit_w / (mbox[2] - mbox[0]), fit_h / (mbox[3] - mbox[1]))
    mcx, mcy = center(mbox)
    tx, ty = canvas_w / 2 - s * mcx, canvas_h / 2 - s * mcy
    out = NEW_FILE_HEADER + [
        '<animated-vector',
        '    xmlns:android="http://schemas.android.com/apk/res/android"',
        '    xmlns:aapt="http://schemas.android.com/aapt">',
        '',
        '    <aapt:attr name="android:drawable">',
        '        <vector',
        '            android:width="%sdp"' % fmt(canvas_w),
        '            android:height="%sdp"' % fmt(canvas_h),
        '            android:viewportWidth="%s"' % fmt(canvas_w),
        '            android:viewportHeight="%s">' % fmt(canvas_h),
    ]
    out += mascot_groups(paths, s, tx, ty, 12, twinkle=loop)
    out += ['        </vector>', '    </aapt:attr>']
    targets = {name: animators(specs, False) for name, specs in INTRO.items()}
    if loop:
        for name, specs in LOOP.items():
            targets[name] = targets.get(name, []) + animators(specs, True)
    for name, lines in targets.items():
        out += ['', '    <target android:name="%s">' % name,
                '        <aapt:attr name="android:animation">',
                '            <set>'] + lines + [
                '            </set>',
                '        </aapt:attr>',
                '    </target>']
    out += ['</animated-vector>', '']
    return '\n'.join(out)


def ntp_logo(paths, original):
    """The CromIKO lockup (mascot and wordmark) in place of the Google logo."""
    letters = [n for letter in WORDMARK for n in letter]
    names = MONO_EVEN_ODD + [RING, HIGHLIGHT, STAR] + letters
    box = bbox(paths, names)
    height, margin = 82, 2
    s = (height - 2 * margin) / (box[3] - box[1])
    width = round((box[2] - box[0]) * s + 2 * margin)
    tx, ty = margin - s * box[0], margin - s * box[1]
    children = path(8, ' '.join(paths[n] for n in MONO_EVEN_ODD), CHARCOAL, True)
    children += path(8, paths[RING], CHARCOAL)
    children += path(8, paths[HIGHLIGHT], ACCENT)
    children += path(8, paths[STAR], ACCENT)
    for letter in WORDMARK:
        children += path(8, ' '.join(paths[n] for n in letter), CHARCOAL, len(letter) > 1)
    # Keep the license header of the original file (and drop a previous CromIKO comment).
    header = original[:original.index('<vector')].split('<!-- CromIKO:')[0]
    out = [header.rstrip('\n'),
           '<!-- CromIKO: the CromIKO logo replaces the Google logo on the new tab page.',
           '     ' + GENERATED + ' -->',
           '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
           '    android:width="%ddp"' % width,
           '    android:height="%ddp"' % height,
           '    android:viewportWidth="%d"' % width,
           '    android:viewportHeight="%d">' % height]
    out += group(4, mapping(s, tx, ty), children)
    out += ['</vector>', '']
    return '\n'.join(out)


def main(svg_path, src_dir):
    paths = load_paths(svg_path)

    def write(rel, content):
        full = os.path.join(src_dir, rel)
        os.makedirs(os.path.dirname(full), exist_ok=True)
        with open(full, 'w', encoding='utf-8') as f:
            f.write(content)
        print('wrote', rel)

    # Splash icon without background: 288dp canvas, content inside a 192dp circle.
    write(SPLASH_ICON, animated_mascot(paths, 288, 288, 156, 130, loop=False))
    # Welcome screen image (110dp high in fre_tosanduma.xml).
    write(WELCOME_MASCOT, animated_mascot(paths, 132, 110, 112, 92, loop=True))
    with open(os.path.join(src_dir, NTP_LOGO), encoding='utf-8') as f:
        original = f.read()
    write(NTP_LOGO, ntp_logo(paths, original))


if __name__ == '__main__':
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])
